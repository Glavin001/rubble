#!/usr/bin/env bash
# Build Rubble's C ABI (engine/crates/engine-ffi) as the static library the Unreal plugin links.
# Pattern from vibe-land's scripts/unreal/build-core.sh.
#
#   scripts/unreal/build-ffi.sh [--platform Mac] [--profile release|debug]
#
# Output (in the plugin's ThirdParty/RubbleFFI):
#   lib/<Platform>/<arch>/librubble_ffi.a
#   lib/<Platform>/<arch>/native-libs.txt   system libraries and frameworks the .a needs
#   lib/<Platform>/<arch>/rubble_ffi.stamp  header sha256 and git commit of this build
#   include-gen/rubble_ffi_build.h          the library's hash (forces a relink when it changes)
#
# The header is not copied: the plugin includes engine/crates/engine-ffi/include/rubble.h
# directly, which engine-ffi's tests keep current.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PLATFORM=""
PROFILE="release"
OUT="$ROOT/unreal/RubbleDemo/Plugins/Rubble/Source/ThirdParty/RubbleFFI"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --platform) PLATFORM="$2"; shift 2 ;;
    --profile) PROFILE="$2"; shift 2 ;;
    -h|--help) sed -n '2,14p' "$0"; exit 0 ;;
    *) echo "build-ffi: unknown argument $1" >&2; exit 2 ;;
  esac
done
if [[ -z "$PLATFORM" ]]; then
  case "$(uname -s)" in
    Darwin) PLATFORM=Mac ;;
    Linux) PLATFORM=Linux ;;
    *) echo "build-ffi: unsupported host $(uname -s); pass --platform" >&2; exit 2 ;;
  esac
fi
case "$PLATFORM" in
  Mac) TRIPLE=aarch64-apple-darwin; ARCH=arm64; LIB=librubble_ffi.a
       export MACOSX_DEPLOYMENT_TARGET=14.0 ;;  # matches UE 5.8's arm64-apple-macos14.00
  Linux) TRIPLE=x86_64-unknown-linux-gnu; ARCH=x86_64; LIB=librubble_ffi.a ;;
  Win64) TRIPLE=x86_64-pc-windows-msvc; ARCH=x64; LIB=rubble_ffi.lib ;;
  *) echo "build-ffi: unknown platform $PLATFORM" >&2; exit 2 ;;
esac

# UBT launched from the editor may not inherit the shell PATH (cargo, and slangc for the shaders).
export PATH="$HOME/.cargo/bin:/opt/homebrew/bin:/usr/local/bin:$PATH"
CARGO="${RUBBLE_CARGO:-$(command -v cargo || echo "$HOME/.cargo/bin/cargo")}"
[[ -x "$CARGO" ]] || { echo "build-ffi: cargo not found (set RUBBLE_CARGO)" >&2; exit 1; }
PROFILE_FLAG=(); PROFILE_DIR=debug
if [[ "$PROFILE" == release ]]; then PROFILE_FLAG=(--release); PROFILE_DIR=release; fi

cd "$ROOT/engine"
NATIVE_LOG="$(mktemp)"
trap 'rm -f "$NATIVE_LOG"' EXIT
# Always -p: the library is engine-ffi's dependency tree only.
"$CARGO" rustc -p engine-ffi --lib "${PROFILE_FLAG[@]}" --target "$TRIPLE" --crate-type staticlib \
  -- --print native-static-libs 2> >(tee "$NATIVE_LOG" >&2)

DEST="$OUT/lib/$PLATFORM/$ARCH"
mkdir -p "$DEST"
TARGET_DIR="$("$CARGO" metadata --format-version 1 --no-deps | python3 -c 'import json,sys; print(json.load(sys.stdin)["target_directory"])')"
cp "$TARGET_DIR/$TRIPLE/$PROFILE_DIR/$LIB" "$DEST/$LIB"
NATIVE="$(sed -n 's/.*native-static-libs: //p' "$NATIVE_LOG" | tail -1)"
printf '%s\n' "$NATIVE" > "$DEST/native-libs.txt"

# UBT does not relink when only a static library changed: a header carrying its hash does.
LIB_SHA="$(shasum -a 256 "$DEST/$LIB" | cut -d' ' -f1)"
GEN="$OUT/include-gen"
mkdir -p "$GEN"
BUILD_H="$GEN/rubble_ffi_build.h"
NEW_H="$(printf '#pragma once\n/* Generated by scripts/unreal/build-ffi.sh: the linked Rubble library. */\n#define RB_FFI_LIB_SHA256 "%s"\n' "$LIB_SHA")"
if [[ ! -f "$BUILD_H" ]] || [[ "$(cat "$BUILD_H")" != "$NEW_H" ]]; then
  printf '%s\n' "$NEW_H" > "$BUILD_H"
fi
HEADER="$ROOT/engine/crates/engine-ffi/include/rubble.h"
HEADER_SHA="$(shasum -a 256 "$HEADER" | cut -d' ' -f1)"
GIT_SHA="$(git -C "$ROOT" rev-parse --short=12 HEAD 2>/dev/null || echo unknown)"
printf 'header_sha256=%s\ngit=%s\ntarget=%s\nprofile=%s\n' "$HEADER_SHA" "$GIT_SHA" "$TRIPLE" "$PROFILE" > "$DEST/rubble_ffi.stamp"
echo "build-ffi: $DEST/$LIB ($(du -h "$DEST/$LIB" | cut -f1)); native libs: ${NATIVE:-none}"
