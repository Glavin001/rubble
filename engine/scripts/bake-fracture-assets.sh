#!/usr/bin/env bash
# Rebuild the fracture lab's assets from Shardwright, reproducibly.
#
# Shardwright (the `prefracture` CLI, crate frac-cli) is taken from either
#   --shardwright PATH (or SHARDWRIGHT_PATH)  an existing local clone, built as it is
#                                            (a warning when it is not at the pinned commit), or
#   SHARDWRIGHT_REV=<commit>                 github.com/Glavin001/Shardwright at that commit
#                                            (cloned and built once under engine/.tools/);
#                                            default: the pinned commit below.
# An asset may name its own Shardwright commit (a fifth field): it is baked with that
# commit, so adding an asset never rebakes the others. A source `gen:NAME` is generated by
# that commit's `prefracture gen-bench --only NAME` (Shardwright's procedural structures).
# Each asset is baked from its Shardwright source mesh and bake config, packaged as one
# self-contained GLB (`export-glb --uncompressed`), and exported for the stress oracle
# (`fracture_stress_export`, level 0). Bakes are deterministic for a given Shardwright
# commit, source, config and seed; the script prints each output's SHA-256 so a rebuild
# can be compared with the recorded one.
#
#   engine/scripts/bake-fracture-assets.sh [--shardwright PATH] [--out DIR] [--only NAME] [--install] [--verify] [--lock]
#   engine/scripts/bake-fracture-assets.sh --shardwright ~/Development/Shardwright
#
# Without --install the GLBs go to DIR (default engine/.tools/baked/); --install copies
# them over engine/crates/engine-webgpu/fracture/assets/ and the oracle packs. Different
# Shardwright commits fracture differently, so installing changes the lab's assets.
# Every run writes DIR/provenance.txt (Shardwright commit, rustc, OS/arch, input hashes,
# output hashes). --lock records the output hashes in engine/scripts/fracture-assets.lock;
# --verify compares against it. Bakes are byte-identical across runs and thread counts on
# one platform; a mismatch on another OS/arch or toolchain is a platform difference to
# investigate, not necessarily a broken bake. --only NAME bakes that asset alone; --lock and
# --verify then touch only its lines. Only .fracphys, .asset.json and the GLBs
# are hashed: Shardwright's report files carry timings.
set -euo pipefail
# The Shardwright commit the lab's rebuilt assets come from (export-glb first appears there).
PINNED_SHARDWRIGHT_REV=e2ea334cbd06181b11a2d793e30582b949af2ece
ENGINE=$(cd "$(dirname "$0")/.." && pwd)
OUT="$ENGINE/.tools/baked"
INSTALL=0
VERIFY=0
LOCK=0
ONLY=
LOCKFILE="$ENGINE/scripts/fracture-assets.lock"
while [ $# -gt 0 ]; do
  case "$1" in
    --out) OUT=$2; shift 2 ;;
    --shardwright) SHARDWRIGHT_PATH=$2; shift 2 ;;
    --install) INSTALL=1; shift ;;
    --verify) VERIFY=1; shift ;;
    --lock) LOCK=1; shift ;;
    --only) ONLY=$2; shift 2 ;;
    *) echo "unknown argument $1" >&2; exit 2 ;;
  esac
done

# The Galleon stern (broadside.html) and the Shardwright commit that adds it.
GALLEON_SHARDWRIGHT_REV=8c8036242076351deaa037d97d0eb3669578b695

# name  source (in the Shardwright checkout, or gen:NAME)  config  level for the oracle  [Shardwright commit]
ASSETS=(
  "veneer-house benchmarks/assets/veneer_house.glb benchmarks/configs/building_lite.toml 0"
  "veneer-house-hull16 benchmarks/assets/veneer_house.glb $ENGINE/crates/engine-webgpu/fracture/assets/veneer-house-hull16.toml 0"
  "masonry-arch benchmarks/assets/masonry_arch.glb benchmarks/configs/building_lite.toml 0"
  "galleon-stern gen:galleon_stern $ENGINE/crates/engine-webgpu/fracture/assets/galleon-stern.toml 2 $GALLEON_SHARDWRIGHT_REV"
)

# shardwright REV: point SW, PF and SW_REV at a built Shardwright for that commit: the
# --shardwright clone as it is (a warning when it is not at REV), or a clone of REV under
# engine/.tools/ (SHARDWRIGHT_REV overrides the default pin, not per-asset pins).
shardwright() {
  local want=$1
  if [ -n "${SHARDWRIGHT_PATH:-}" ]; then
    SW=$(cd "$SHARDWRIGHT_PATH" && pwd)
    SW_REV="$(git -C "$SW" rev-parse HEAD)$(git -C "$SW" diff --quiet && git -C "$SW" diff --cached --quiet || echo -dirty)"
    if [ "$SW_REV" != "$want" ]; then
      echo "warning: $SW is at $SW_REV, not the pinned $want: its bakes may differ from the recorded assets" >&2
    fi
  else
    SW="$ENGINE/.tools/shardwright-$want"
    if [ ! -d "$SW/.git" ]; then
      git clone --filter=blob:none https://github.com/Glavin001/Shardwright.git "$SW"
    fi
    git -C "$SW" fetch -q origin "$want" || true
    git -C "$SW" checkout -q "$want"
    SW_REV=$want
  fi
  (cd "$SW" && cargo build --release -q -p frac-cli)
  PF="$SW/target/release/prefracture"
  "$PF" export-glb --help > /dev/null 2>&1 || { echo "this Shardwright ($SW_REV) has no export-glb" >&2; exit 1; }
}
DEFAULT_REV=${SHARDWRIGHT_REV:-$PINNED_SHARDWRIGHT_REV}
shardwright "$DEFAULT_REV"
REV=$SW_REV

mkdir -p "$OUT"
echo "Shardwright $REV"
PROV="$OUT/provenance.txt"
{
  echo "shardwright $REV"
  echo "rustc $(cd "$SW" && rustc -V)"
  echo "platform $(uname -sm)"
} > "$PROV"
HASHES="$OUT/hashes.txt"
: > "$HASHES"
for entry in "${ASSETS[@]}"; do
  read -r name source config level rev <<< "$entry"
  [ -n "$ONLY" ] && [ "$name" != "$ONLY" ] && continue
  shardwright "${rev:-$DEFAULT_REV}"
  [ -n "$rev" ] && echo "shardwright $name $SW_REV" >> "$PROV"
  case "$config" in /*) ;; *) config="$SW/$config" ;; esac
  work="$OUT/$name.bake"
  rm -rf "$work"
  mkdir -p "$work"
  case "$source" in
    gen:*)
      "$PF" gen-bench --out "$work/src" --only "${source#gen:}" > /dev/null
      source="$work/src/${source#gen:}.glb" ;;
    *) source="$SW/$source" ;;
  esac
  "$PF" bake --input "$source" --config "$config" --out "$work/" | tail -1
  stem=$(basename "$source" .glb)
  "$PF" export-glb --input "$work/$stem.glb" --physics "$work/$stem.fracphys" --out "$OUT/$name.glb" --uncompressed > /dev/null
  cargo run -q --manifest-path "$ENGINE/Cargo.toml" -p engine-fracture --bin fracture_stress_export -- \
    "$OUT/$name.glb" "$OUT/$name-l$level.json" "$level"
  echo "input $name $(shasum -a 256 "$source" | cut -c1-64) $(shasum -a 256 "$config" | cut -c1-64)" >> "$PROV"
  (cd "$OUT" && shasum -a 256 "$name.bake/$stem.fracphys" "$name.bake/$stem.asset.json" "$name.glb" "$name-l$level.json") | tee -a "$HASHES"
  if [ "$INSTALL" = 1 ]; then
    cp "$OUT/$name.glb" "$ENGINE/crates/engine-webgpu/fracture/assets/$name.glb"
    [ "$name" = veneer-house ] && cp "$OUT/$name-l$level.json" "$ENGINE/stress-oracle/packs/veneer-house-l$level.json"
  fi
done
cat "$HASHES" >> "$PROV"
# The lock's lines for the assets baked this run (all, or --only's).
mine() { if [ -n "$ONLY" ]; then grep -E "^[0-9a-f]{64}  $ONLY[.-]"; else grep -v '^#'; fi; }
if [ "$LOCK" = 1 ]; then
  if [ -n "$ONLY" ]; then
    { grep -vE "^[0-9a-f]{64}  $ONLY[.-]" "$LOCKFILE"; cat "$HASHES"; } > "$LOCKFILE.new"
    mv "$LOCKFILE.new" "$LOCKFILE"
  else
    { echo "# Output SHA-256 of engine/scripts/bake-fracture-assets.sh; $(head -3 "$PROV" | tr '\n' ';')"; cat "$HASHES"; } > "$LOCKFILE"
  fi
  echo "recorded $LOCKFILE"
fi
if [ "$VERIFY" = 1 ]; then
  if diff <(mine < "$LOCKFILE") "$HASHES"; then
    echo "verify: every output matches $LOCKFILE"
  else
    echo "verify: outputs differ from $LOCKFILE (platform/toolchain or Shardwright difference; see $PROV)" >&2
    exit 1
  fi
fi
