//! The committed header is the one the current sources generate.

#[test]
fn committed_header_is_current() {
    let generated = std::fs::read_to_string(concat!(env!("OUT_DIR"), "/rubble.h")).unwrap();
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/include/rubble.h");
    if std::env::var("RUBBLE_FFI_BLESS").is_ok() {
        std::fs::write(path, &generated).unwrap();
    }
    // A Windows checkout may have CRLF line endings; compare the text.
    let committed = std::fs::read_to_string(path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    assert!(
        committed == generated.replace("\r\n", "\n"),
        "include/rubble.h is stale: run `RUBBLE_FFI_BLESS=1 cargo test -p engine-ffi --test header`"
    );
}

/// Every exported function is declared in the header (cbindgen skips
/// functions it cannot see, such as ones generated by macros).
#[test]
fn every_export_is_in_the_header() {
    let src = include_str!("../src/lib.rs");
    let header = include_str!("../include/rubble.h");
    let missing: Vec<&str> = src
        .split("extern \"C\" fn ")
        .skip(1)
        .filter_map(|rest| rest.split('(').next())
        .filter(|name| {
            let call = format!("{name}(");
            !header.match_indices(&call).any(|(i, _)| {
                let before = header[..i].chars().next_back().unwrap_or(' ');
                !(before.is_alphanumeric() || before == '_')
            })
        })
        .collect();
    assert!(missing.is_empty(), "not in rubble.h: {missing:?}");
}
