/// The glyph of a character; characters without one render as `?`.
pub fn glyph(c: char) -> [u8; 5] {
    match c {
        ' '..='~' => ASCII[c as usize - 0x20],
        '×' => [0x22, 0x14, 0x08, 0x14, 0x22],
        '°' => [0x00, 0x06, 0x09, 0x09, 0x06],
        'σ' => [0x38, 0x44, 0x44, 0x3c, 0x04],
        '≥' => [0x51, 0x51, 0x4a, 0x4a, 0x44],
        '±' => [0x44, 0x44, 0x5f, 0x44, 0x44],
        'Δ' => [0x60, 0x58, 0x46, 0x58, 0x60],
        '·' => [0x00, 0x00, 0x08, 0x00, 0x00],
        '—' => [0x08, 0x08, 0x08, 0x08, 0x08],
        _ => ASCII['?' as usize - 0x20],
    }
}

/// Width in pixels of `text` drawn at `scale` (no trailing spacing).
pub fn text_width(text: &str, scale: usize) -> usize {
    let n = text.chars().count();
    if n == 0 {
        0
    } else {
        (n * ADVANCE - 1) * scale
    }
}

/// Height in pixels of one line of text at `scale`.
pub fn text_height(scale: usize) -> usize {
    GLYPH_H * scale
}

/// Calls `plot(x, y)` for every lit font pixel of `text` (font-pixel coordinates,
/// origin at the top-left of the first glyph).
pub fn for_each_pixel(text: &str, mut plot: impl FnMut(usize, usize)) {
    for (i, c) in text.chars().enumerate() {
        for (col, bits) in glyph(c).iter().enumerate() {
            for row in 0..GLYPH_H {
                if bits >> row & 1 == 1 {
                    plot(i * ADVANCE + col, row);
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn widths_and_fallback() {
        assert_eq!(text_width("", 3), 0);
        assert_eq!(text_width("A", 1), 5);
        assert_eq!(text_width("AB", 2), 22);
        assert_eq!(glyph('\u{2603}'), glyph('?'));
        assert_eq!(glyph(' '), [0; 5]);
    }

    #[test]
    fn pixels_follow_the_column_bits() {
        let mut lit = Vec::new();
        for_each_pixel("|", |x, y| lit.push((x, y)));
        // '|' is a full-height bar in the middle column (above the descender row).
        assert_eq!(lit, (0..7).map(|y| (2, y)).collect::<Vec<_>>());
        let mut p = Vec::new();
        for_each_pixel("p", |x, y| p.push((x, y)));
        assert!(p.contains(&(0, 7)), "p descends");
        let mut second = Vec::new();
        for_each_pixel(" .", |x, y| second.push((x, y)));
        assert!(second.iter().all(|&(x, y)| x >= ADVANCE && y >= 5));
    }
}
