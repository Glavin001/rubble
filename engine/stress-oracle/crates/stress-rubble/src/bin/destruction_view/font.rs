//! Embedded 5x7 bitmap font (the classic HD44780-style ASCII set, with true
//! descenders for g, j, p, q, y in an eighth row) plus the few symbols the labels use
//! (×, °, σ, ≥, ±, Δ, ·).
//!
//! Each glyph is 5 column bytes; bit 0 is the top row, bit 6 the baseline row and bit 7
//! the descender row. Text is drawn by scaling every font pixel to an integer
//! `scale x scale` block, so it stays crisp.

pub const GLYPH_W: usize = 5;
/// Cell height including the descender row.
pub const GLYPH_H: usize = 8;
/// Horizontal advance per character, in font pixels (glyph plus one column of spacing).
pub const ADVANCE: usize = GLYPH_W + 1;

